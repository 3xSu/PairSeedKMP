/**
 * 查重规范化（《工作链路·查重链路》1.1 第一闸前置，短词 / 长文共用）：
 * 全角 → 半角、英文小写、简繁归一、去空白、去标点。
 *
 * 简繁表是**起步子集**：只收常用字一对一映射；多音 / 多义字（著、乾、瞭、藉 这类
 * 一繁对多简的）不收——宁缺勿错，未收录字形按原文比较。范围与抽查结论见
 * `.agent-docs/.tests/查重链路.md`。
 */
fun normalize(text: String): String {
    val out = StringBuilder(text.length)
    for (ch in text) {
        var c = toHalfWidth(ch)
        c = c.lowercaseChar()
        c = TRAD_TO_SIMP[c] ?: c
        // 不间断空格（U+00A0）显式列出：各平台 isWhitespace 判定不一致（JVM 不算、Unicode 属性算）
        if (c.isWhitespace() || c.code == 0xA0 || c in PUNCTUATION) continue
        out.append(c)
    }
    return out.toString()
}

/** 全角 → 半角（ASCII 可见区 U+FF01–U+FF5E、全角空格 U+3000 → 空白）。 */
private fun toHalfWidth(ch: Char): Char = when {
    ch == '　' -> ' '
    ch in '！'..'～' -> ch - 0xFEE0
    else -> ch
}

